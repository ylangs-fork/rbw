#!/usr/bin/python3
"""Disposable synthetic account pinentry. Password comes only from private HOME."""
import json
import os
import pathlib
import sys

home = pathlib.Path(os.environ["HOME"])
print("OK disposable synthetic pinentry", flush=True)
for line in sys.stdin:
    command = line.strip().split(" ", 1)[0]
    if command == "GETPIN":
        with (home / "pinentry-events").open("a", encoding="ascii") as events:
            events.write("GETPIN\n")
        if (home / "pinentry-allow").read_text().strip() != "allow":
            print("ERR 83886179 Operation cancelled", flush=True)
        else:
            password = json.loads((home / "credentials.json").read_text())["password"]
            # Passwords generated by the harness are URL-safe ASCII.
            print("D " + password, flush=True)
            print("OK", flush=True)
    elif command == "BYE":
        print("OK", flush=True)
        break
    else:
        print("OK", flush=True)
